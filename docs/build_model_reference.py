"""Generate docs/MODEL_EVALUATION_REFERENCE.md from the saved evaluation outputs (no training, no model loading).

Sources: data_warehouse/artifacts/artifact_manifest.json, reports/model_evaluation/**/results.json, forecasting and
segmentation outputs, artifacts/training_provenance.json and the latest restoration audit.
Run from the project root:  .venv\\Scripts\\python docs\\build_model_reference.py
"""
from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DW = ROOT / "data_warehouse"
OUT = ROOT / "docs" / "MODEL_EVALUATION_REFERENCE.md"


def f(v, d=3):
    return "—" if v is None or (isinstance(v, float) and v != v) else (f"{v:.{d}f}" if isinstance(v, (int, float)) else str(v))


def results(task: str, zone: str) -> dict:
    p = DW / "reports" / "model_evaluation" / zone.lower() / task / "results.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else {}


def headline(kind: str, m: dict) -> str:
    if kind == "binary":
        return f"ROC-AUC {f(m.get('test_roc_auc'))} · PR-AUC {f(m.get('test_pr_auc'))} · F1 {f(m.get('test_tuned_f1'))} · Brier {f(m.get('test_brier'))}"
    if kind == "multiclass":
        return f"macro-F1 {f(m.get('test_f1_macro'))} · ROC-AUC (OvR) {f(m.get('test_roc_auc_ovr_macro'))} · accuracy {f(m.get('test_accuracy'))}"
    if kind == "regression":
        return f"RMSE {f(m.get('test_rmse'))} · MAE {f(m.get('test_mae'))} · R² {f(m.get('test_r2'))}"
    return ""


def main():
    man = json.loads((DW / "artifacts" / "artifact_manifest.json").read_text(encoding="utf-8"))
    prov_p = DW / "artifacts" / "training_provenance.json"
    prov = json.loads(prov_p.read_text(encoding="utf-8")) if prov_p.exists() else {"tasks": {}}
    L = ["# Model evaluation reference", "",
         "Generated by `docs/build_model_reference.py` from the saved evaluation outputs. **All institutional models are trained "
         "on SYNTHETIC data and are demonstration models, not valid for decisions about real students.** UCI models are "
         "benchmarks on the public UCI dataset (Portugal) and are not transferable to another institution.", "",
         "Common methodology (unchanged since Batch 1):",
         "",
         "- **Splits:** a student-grouped holdout (25% of students form the untouched test set; StratifiedGroupKFold with seed 20261110), then 5-fold grouped cross-validation on the training students.",
         "- **Model selection:** by the cross-validation metric only. The test set is never used for selection.",
         "- **Threshold:** the original threshold maximises class-1 F1 on the cross-validation out-of-fold predictions.",
         "- **Robustness:** an out-of-time check where available.",
         "- **Leakage gate:** every task must pass all of its leakage checks.",
         "- **Explanations:** TreeSHAP or coefficient-based. These are associations, not causes.", "",
         "## 1. All 20 tasks", "",
         "| # | Task | Batch | Kind | Data | Status | Selected model | Test performance (selected model) | Trained in |",
         "|---|---|---|---|---|---|---|---|---|"]
    for i, (task, e) in enumerate(man["tasks"].items(), 1):
        r = results(task, e.get("zone", "SYNTHETIC")) if e["kind"] in ("binary", "multiclass", "regression", "survival") else {}
        perf = headline(e["kind"], e.get("test_metrics_selected") or {})
        if e["kind"] == "survival":
            perf = f"concordance test {f(r.get('concordance_test'))} (train {f(r.get('concordance_train'))})"
        if task == "forecasting":
            perf = "13 series families; selection by backtest WAPE (see §4)"
        if task == "syn_segmentation":
            perf = "k-means k=4 silhouette 0.190 (weak) + isolation forest 2 % (see §5)"
        where = prov["tasks"].get(task, {}).get("environment", "—")
        L.append(f"| {i} | `{task}` | {e.get('batch')} | {e['kind']} | {e.get('zone')} | {e['status']} | {e.get('selected_model') or '—'} | {perf} | {where} |")

    L += ["", "## 2. Supervised models: candidate comparison (test set)", ""]
    for task, e in man["tasks"].items():
        if e["kind"] not in ("binary", "multiclass", "regression"):
            continue
        r = results(task, e["zone"])
        if not r:
            continue
        L += [f"### {r.get('title', task)} (`{task}`)", "",
              f"- **Target:** {r.get('target_definition', '—')}",
              f"- **Prediction point:** {r.get('prediction_point', '—')}",
              f"- **Rows / features:** {r.get('n_rows')} / {r.get('n_features')} · selection rule: {r.get('selection_rule')} → **{r.get('best_model')}**"]
        if e.get("thresholds"):
            L.append(f"- **Thresholds:** " + "; ".join(f"{k} = {f(v) if isinstance(v, (int, float)) else v}" for k, v in e["thresholds"].items() if k != "original_rule"))
        b = r.get("best_vs_linear_baseline")
        if b:
            L.append(f"- **Best vs linear baseline:** {b['metric']} {f(b['best'])} vs {f(b['linear_baseline'])} (Δ {f(b['difference'])}; CV SD {f(b.get('cv_sd_best'))})")
            try:
                noise = abs(float(b["difference"])) <= float(b.get("cv_sd_best") or 0)
            except (TypeError, ValueError):
                noise = False
            L.append("- **Interpretation:** " + ("the selected model's advantage over the linear baseline is within one CV standard deviation, so the two are "
                     "practically equivalent; the simpler model is a defensible alternative." if noise else
                     "the selected model is ahead of the linear baseline by more than one CV standard deviation."))
        sel = (e.get("models") or {}).get(e.get("selected_model"), {})
        if sel.get("path"):
            loc = man["files"].get(sel["path"], {}).get("persistent_location", "—")
            L.append(f"- **Saved artifact:** `data_warehouse/{sel['path']}` · persistent copy `{loc}`")
        L.append("- **Limitations:** " + ("benchmark on the public UCI dataset (one Portuguese institution, 2008–2019 cohorts); not transferable to another institution."
                 if e["zone"] == "UCI" else "trained on synthetic demonstration data whose relationships were configured by the generator; "
                 "metrics show the pipeline works, not real-world predictive validity."))
        cols = {"binary": ["cv_pr_auc", "test_roc_auc", "test_pr_auc", "test_tuned_precision", "test_tuned_recall", "test_tuned_f1", "test_brier"],
                "multiclass": ["cv_f1_macro", "test_f1_macro", "test_roc_auc_ovr_macro", "test_accuracy"],
                "regression": ["cv_rmse", "test_rmse", "test_mae", "test_r2"]}[e["kind"]]
        L += ["", "| Model | " + " | ".join(cols) + " |", "|---|" + "---|" * len(cols)]
        for m in r.get("models", []):
            L.append(f"| {m['model']}{' ✔' if m['model'] == r.get('best_model') else ''} | " + " | ".join(f(m.get(c)) for c in cols) + " |")
        oot = r.get("out_of_time")
        if oot and oot.get("metrics"):
            L += ["", "Out-of-time (" + str(oot.get("cutoff")) + "): " + " · ".join(f"{k} {f(v)}" for k, v in oot["metrics"].items() if isinstance(v, float))]
        L.append("")

    L += ["## 3. Survival models (Cox proportional hazards)", ""]
    for task in ("syn_graduation_cox", "syn_dropout_cox"):
        r = results(task, "SYNTHETIC")
        if not r:
            continue
        L += [f"### `{task}`", "",
              f"- **Concordance:** test {f(r.get('concordance_test'))} (train {f(r.get('concordance_train'))}); events {r.get('events')} / censored {r.get('censored')}",
              f"- **Proportional-hazards assumption questionable for:** {', '.join(r.get('ph_possible_violations', [])) or 'none'}. Their hazard ratios are time-averaged.",
              "", "| Covariate | HR per SD | 95 % CI | p |", "|---|---|---|---|"]
        for h in r.get("hazard_ratios", []):
            L.append(f"| {h['covariate']} | {f(h.get('hazard_ratio_per_sd'))} | {f(h.get('ci_low'))}–{f(h.get('ci_high'))} | {f(h.get('p_value'), 4)} |")
        L.append("")

    fr = DW / "reports" / "forecasting"
    if (fr / "best_method_by_series_family.csv").exists():
        best = pd.read_csv(fr / "best_method_by_series_family.csv")
        cov = pd.read_csv(fr / "backtest_summary_by_series_method.csv")
        L += ["## 4. Forecasting", "",
              "Rolling-origin backtests. The method for each series family is selected by WAPE; failed fits are recorded and never selected. "
              "80 % prediction intervals are empirical (from backtest errors).", "",
              "| Series family | Selected method | WAPE | Seasonal-naive WAPE | 80 % PI coverage (selected) |", "|---|---|---|---|---|"]
        for _, b in best.iterrows():
            c = cov[(cov.series == b.series) & (cov.method == b.best_method)]
            L.append(f"| {b.series} | {b.best_method} | {f(b.best_wape)} | {f(b.seasonal_naive_wape)} | {f(c.pi80_coverage.iloc[0]) if len(c) else '—'} |")
        m = cov.groupby("method").pi80_coverage.mean()
        L += ["", "Mean 80 % interval coverage by method across families: " + " · ".join(f"{k} {f(v)}" for k, v in m.items())
              + ". Coverage well below 0.80 (notably ETS) means intervals are too narrow.", ""]

    sp = DW / "reports" / "feature_analysis" / "synthetic" / "segmentation_results.json"
    if sp.exists():
        s = json.loads(sp.read_text(encoding="utf-8"))
        q = s.get("cluster_quality", {})
        L += ["## 5. Segmentation and anomalies", "",
              f"- **Population:** {s.get('n_students')} students. **k = {s.get('chosen_k')}**, chosen by silhouette over k = 2–8. Silhouette {f(q.get('silhouette_kmeans_chosen_k_full_data'))}, which is **weak structure**. Davies–Bouldin {f(q.get('davies_bouldin_kmeans'))}; k-means vs Ward adjusted Rand index {f(s.get('kmeans_vs_ward_adjusted_rand'))}.",
              f"- **Anomalies:** isolation forest with contamination 2 % flagged {s.get('isolation_forest', {}).get('flagged')} records. These are unusual records for data-quality review, **not evidence of misconduct**.", ""]

    ap = DW / "artifacts" / "restoration_audit.json"
    if ap.exists():
        a = json.loads(ap.read_text(encoding="utf-8"))
        L += ["## 6. Restoration audit (local inference, no training)", "",
              f"Audit {a['audit_utc']} on {a['environment']}: **{a['status_counts']}** over {a['artifacts_audited']} artifacts.", "",
              "| Task | Model | Role | Loaded via | Status | Error |", "|---|---|---|---|---|---|"]
        for r in a["records"]:
            L.append(f"| `{r['task']}` | {r['model']} | {r.get('role', '')} | {r.get('loaded_via', '—')} | **{r['final_status']}** | {'; '.join(r.get('errors', []))[:120]} |")
        L.append("")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote", OUT, len(L), "lines")


if __name__ == "__main__":
    main()
